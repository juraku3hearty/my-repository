#!/bin/bash
# 00〜07 の .gs を1ファイルに連結して ALL_IN_ONE.gs を生成する。
# GASは全ファイルが同一スコープなので、連結しても動作は変わらない。
# 編集は必ず元の 00〜07 側で行い、このスクリプトで再生成すること。
set -e
cd "$(dirname "$0")"

out=ALL_IN_ONE.gs
{
  echo "/**"
  echo " * ALL_IN_ONE.gs — 00_Config 〜 07_Setup を1ファイルに連結した自動生成ファイル"
  echo " *"
  echo " * GASへの貼り付けを1回で済ませるための版。"
  echo " * このファイルを直接編集しないこと。編集は 00〜07 の各ファイルで行い、"
  echo " * ./build_all_in_one.sh を実行して再生成する。"
  echo " *"
  echo " * 生成元: $(ls 0[0-7]_*.gs | tr '\n' ' ')"
  echo " */"
  for f in 0[0-7]_*.gs; do
    echo
    echo "// ═══════════════════════════════════════════════════════════"
    echo "// $f"
    echo "// ═══════════════════════════════════════════════════════════"
    echo
    cat "$f"
  done
} > "$out"

echo "生成: $out ($(wc -l < "$out") 行)"
